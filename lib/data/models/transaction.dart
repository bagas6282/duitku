/// One ledger entry.
///
/// [type] is a [TxType] name stored as text so the column stays readable in a
/// raw SQLite browser — handy while debugging, and immune to enum reordering.
///
/// [id] is nullable so a row can exist in memory before it is inserted; the
/// repository assigns the real rowid on `insert`.
class Transaction {
  const Transaction({
    this.id,
    required this.type,
    required this.amount,
    required this.categoryId,
    required this.walletId,
    required this.date,
    this.note,
    this.recurringId,
    this.transferWalletId,
    this.createdAt,
  });

  final int? id;
  final TxType type;
  final num amount;
  final int categoryId;
  final int walletId;

  /// When the money moved. Named `date` because that is how users think about
  /// it; the column is `occurred_at`.
  final DateTime date;

  final String? note;

  /// Set when this row was generated by a recurring rule.
  final int? recurringId;

  /// Destination wallet for [TxType.transfer] rows.
  final int? transferWalletId;

  /// Insert timestamp, used only for stable ordering of same-day rows.
  final DateTime? createdAt;

  bool get isIncome => type == TxType.income;
  bool get isTransfer => type == TxType.transfer;

  /// Transfers move money sideways, so they never count as income or expense.
  num get signedAmount => switch (type) {
        TxType.income => amount,
        TxType.expense => -amount,
        TxType.transfer => 0,
      };

  Transaction copyWith({
    int? id,
    TxType? type,
    num? amount,
    int? categoryId,
    int? walletId,
    DateTime? date,
    String? note,
    int? recurringId,
    int? transferWalletId,
    DateTime? createdAt,
  }) {
    return Transaction(
      id: id ?? this.id,
      type: type ?? this.type,
      amount: amount ?? this.amount,
      categoryId: categoryId ?? this.categoryId,
      walletId: walletId ?? this.walletId,
      date: date ?? this.date,
      note: note ?? this.note,
      recurringId: recurringId ?? this.recurringId,
      transferWalletId: transferWalletId ?? this.transferWalletId,
      createdAt: createdAt ?? this.createdAt,
    );
  }

  /// Same row with a different saved amount.
  ///
  /// Explicit because [copyWith] treats a null argument as "keep the old
  /// value", so a note cannot be cleared and a partial amount cannot be
  /// distinguished from "unchanged".
  Transaction withAmount(num newAmount, {String? newNote}) {
    return Transaction(
      id: id,
      type: type,
      amount: newAmount,
      categoryId: categoryId,
      walletId: walletId,
      date: date,
      note: newNote ?? note,
      recurringId: recurringId,
      transferWalletId: transferWalletId,
      createdAt: createdAt,
    );
  }

  Map<String, Object?> toMap() => {
        if (id != null) 'id': id,
        'type': type.name,
        'amount': amount,
        'category_id': categoryId,
        'wallet_id': walletId,
        'occurred_at': date.millisecondsSinceEpoch,
        // The column is NOT NULL: an absent note must persist as '' rather
        // than null, or every plain expense would fail to save.
        'note': note ?? '',
        'recurring_id': recurringId,
        'transfer_wallet_id': transferWalletId,
        'created_at': (createdAt ?? DateTime.now()).millisecondsSinceEpoch,
      };

  static Transaction fromMap(Map<String, Object?> m) => Transaction(
        id: m['id'] as int?,
        type: TxType.values.firstWhere(
          (t) => t.name == m['type'],
          orElse: () => TxType.expense,
        ),
        amount: m['amount']! as num,
        categoryId: (m['category_id'] ?? 0) as int,
        walletId: m['wallet_id']! as int,
        date: DateTime.fromMillisecondsSinceEpoch(m['occurred_at']! as int),
        note: m['note'] as String?,
        recurringId: m['recurring_id'] as int?,
        transferWalletId: m['transfer_wallet_id'] as int?,
        createdAt: m['created_at'] == null
            ? null
            : DateTime.fromMillisecondsSinceEpoch(m['created_at']! as int),
      );
}

enum TxType { income, expense, transfer }
